//! Alien SDK for Rust: a thin facade over the generated BAML SDK (`alien_api`).
//!
//! It builds clients, converts errors and picks the public surface; every
//! behavior lives in the BAML project (`baml/baml_src`).
//!
//! ```no_run
//! use alien_sdk::{Alien, Options};
//!
//! # async fn run() -> Result<(), alien_sdk::Error> {
//! let alien = Alien::new(Options::default())?; // API key from ALIEN_API_KEY
//! let me = alien.auth().whoami().send().await?;
//! let page = alien.deployments().list().project("my-project").limit(10).send().await?;
//! # Ok(()) }
//! ```
//!
//! Every operation is a method of [`Alien`] or [`AlienManager`], grouped as in
//! Alien's TypeScript SDK (`alien.deployment_groups().create_token(id)`; an
//! operation without a group is a method of the client itself,
//! `alien.accept_workspace_invitation(token)`). The method takes the
//! operation's required arguments and returns a builder
//! ([`operations::platform`], [`operations::manager`]) with a setter per
//! optional argument, `baml_options` for per-call options ([`BamlOptions`],
//! a timeout for example), and an async `send()`. Request and response types
//! are in [`platform`] and [`manager`]. [`init`] and [`shutdown`] block.
//!
//! Telemetry is on (`medium`) unless `ALIEN_TELEMETRY=off`; see [`shutdown`]
//! for when to call it.

use std::{collections::HashMap, convert::Infallible, fmt, time::Duration};

use alien_api::setup;

/// The builders of every Platform and Manager API operation (generated by
/// genops into `src/operations.rs`).
pub mod operations;

/// Every Platform and Manager API request and response type, as generated.
pub use operations::types::{manager, platform};

pub use alien_api::setup::CloudFormationLaunch;

/// Per-call options, set on a builder with `.baml_options(..)`, for example
/// `BamlOptions::new().timeout_ms(10_000)` (the default timeout is 5 minutes).
pub use alien_api::BamlOptions;

/// The types generated fields use: `json` fields are [`Json`]
/// (`serde_json::Value`), maps are [`Map`] (an insertion-ordered map).
pub use baml_bridge::{Json, Map, serde_json};

/// The Platform API used when [`Options::server_url`] is `None`.
pub const DEFAULT_SERVER_URL: &str = "https://api.alien.dev";

/// Read by [`Alien::new`] when [`Options::api_key`] is `None`, as Alien's
/// TypeScript SDK and CLI do.
const API_KEY_ENV: &str = "ALIEN_API_KEY";

/// What `Debug` output shows instead of a secret.
const REDACTED: &str = "<redacted>";

/// `url` with its query string, which can carry a credential, redacted.
fn redact_query(url: &str) -> String {
    match url.split_once('?') {
        Some((base, _)) => format!("{base}?{REDACTED}"),
        None => url.to_string(),
    }
}

/// The error every Alien SDK call returns for a failure the SDK describes
/// (docs/errors.md). Its fields are named as in `alien_error::AlienError`,
/// plus `request_id`.
///
/// [`source`](Self::source) is the error the server names as this one's
/// cause, and `std::error::Error::source()` returns it, so anything that
/// walks an error's sources walks the server's chain.
///
/// The struct is `#[non_exhaustive]`: it gains a field when Alien's error
/// does, so read its fields rather than matching on all of them.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub struct AlienError {
    pub code: String,
    pub message: String,
    pub retryable: bool,
    /// The HTTP status of the response that failed, if there was one. On a
    /// `source` level: the status that level names, if any.
    pub http_status_code: Option<u16>,
    pub context: Option<HashMap<String, String>>,
    /// The server's remediation hint, if it sent one.
    pub hint: Option<String>,
    /// The server's request ID (the error body's `requestId`), if it sent one.
    pub request_id: Option<String>,
    /// The error that caused this one, from the server's `source` chain (at
    /// most 8 levels below the returned error).
    pub source: Option<Box<AlienError>>,
    /// The server's `internal` flag; `None` when the error is not from a
    /// server's error body.
    pub internal: Option<bool>,
}

impl fmt::Display for AlienError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}", self.code, self.message)
    }
}

impl std::error::Error for AlienError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        self.source
            .as_deref()
            .map(|source| source as &(dyn std::error::Error + 'static))
    }
}

impl From<alien_api::errors::AlienError> for AlienError {
    fn from(value: alien_api::errors::AlienError) -> Self {
        // Every field by name, without `..`: when BAML's AlienError gains a
        // field, this stops compiling until the field is mapped below.
        let alien_api::errors::AlienError {
            code,
            message,
            retryable,
            http_status,
            context,
            hint,
            request_id,
            source,
            internal,
        } = value;
        Self {
            code,
            message,
            retryable,
            // The response's status, or on a `source` level a number the
            // server wrote, which the BAML code keeps only from 100 to 599.
            // One that still does not fit is dropped, never a panic.
            http_status_code: http_status.and_then(|status| u16::try_from(status).ok()),
            context: context.map(|context| context.into_iter().collect()),
            hint,
            request_id,
            source: source.map(|source| Box::new(Self::from(*source))),
            internal,
        }
    }
}

/// An SDK call failure.
#[derive(Debug)]
#[non_exhaustive]
pub enum Error {
    /// The call failed in a way the SDK describes (docs/errors.md).
    /// `source()` is the held error's: the server's `source` chain.
    Alien(AlienError),
    /// The BAML runtime failed: it could not start or was shut down, a
    /// blocking function was called inside an async runtime, a value has no
    /// Rust form (a `json` integer outside `i64`/`u64` in a response, docs/gaps.md#b19),
    /// or BAML panicked. Holds the `baml_bridge` error, BAML trace included;
    /// `Display` and `source()` are the held error's.
    Runtime(Box<dyn std::error::Error + Send + Sync>),
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Error::Alien(error) => error.fmt(f),
            Error::Runtime(error) => error.fmt(f),
        }
    }
}

impl std::error::Error for Error {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            // `Error::Alien` is the error itself, not a wrapper around it:
            // its source is the error's own.
            Error::Alien(error) => std::error::Error::source(error),
            Error::Runtime(error) => error.source(),
        }
    }
}

impl From<baml_bridge::Error<alien_api::errors::AlienError>> for Error {
    fn from(error: baml_bridge::Error<alien_api::errors::AlienError>) -> Self {
        match error {
            baml_bridge::Error::Thrown { value, .. } => Error::Alien((*value).into()),
            other => Error::Runtime(Box::new(other)),
        }
    }
}

impl From<baml_bridge::Error> for Error {
    fn from(error: baml_bridge::Error) -> Self {
        Error::Runtime(Box::new(error))
    }
}

/// Starts the BAML runtime now rather than on the first call, so that a
/// failure to start shows here. Blocks. After [`shutdown`] it returns `Ok` but
/// does not restart the runtime.
pub fn init() -> Result<(), Error> {
    Ok(alien_api::init()?)
}

/// Shuts the SDK's runtime down: waits for calls in flight and seals the
/// telemetry recording. SDK calls made afterwards fail with
/// [`Error::Runtime`] for the rest of the process ([`init`] does not restart
/// it). Calling it again returns `Ok`.
///
/// It blocks until every call in flight has finished, with no time limit
/// (each call can run up to its timeout, 5 minutes by default). From async
/// code, run it with `tokio::task::spawn_blocking`.
///
/// The runtime does this by itself when the process exits normally (`main`
/// returns, or `std::process::exit` on Unix), with the same wait and no time limit.
/// Unless telemetry is off (`ALIEN_TELEMETRY=off`), call `shutdown()` before
/// the process ends any other way: a signal (handle SIGTERM, for example in a
/// container with a 30-second grace period), `std::process::abort`,
/// `panic = "abort"`, or `std::process::exit` on Windows. Otherwise the
/// recording is not sealed (docs/runtime.md).
pub fn shutdown() -> Result<(), Error> {
    baml_bridge::runtime::shutdown()
        .map_err(|error| Error::from(baml_bridge::Error::<Infallible>::Sdk(error)))
}

/// How to reach the Platform API: Alien's TypeScript SDK options (`apiKey`,
/// `serverURL`, `workspace`, `timeoutMs`) in snake_case. Its `Debug` output
/// never shows the API key.
#[derive(Clone, Default)]
pub struct Options {
    /// Sent as a Bearer token. When `None`, [`Alien::new`] reads it from the
    /// `ALIEN_API_KEY` environment variable, as Alien's TypeScript SDK does.
    /// An empty key, or none at all, makes [`Alien::new`] fail.
    pub api_key: Option<String>,
    /// Defaults to [`DEFAULT_SERVER_URL`].
    pub server_url: Option<String>,
    /// Optional for workspace-scoped API keys.
    pub workspace: Option<String>,
    /// Limit for each HTTP request, from connecting to reading the whole
    /// response, rounded up to whole milliseconds. `None`: BAML's default of 5
    /// minutes; `Some(Duration::ZERO)`: no limit. A request that runs out fails
    /// with `COMMUNICATION_ERROR` (retryable). A per-call timeout
    /// ([`BamlOptions::timeout_ms`]) limits the whole call as well: the shorter
    /// one ends it.
    pub timeout: Option<Duration>,
}

impl fmt::Debug for Options {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Options")
            .field("api_key", &self.api_key.as_ref().map(|_| REDACTED))
            .field("server_url", &self.server_url.as_deref().map(redact_query))
            .field("workspace", &self.workspace)
            .field("timeout", &self.timeout)
            .finish()
    }
}

/// The largest BAML `int`: the generated clients hold the timeout as one.
const MAX_TIMEOUT_MS: u128 = (1 << 62) - 1;

/// A client timeout as the generated clients take it: whole milliseconds,
/// rounded up so that a sub-millisecond timeout still limits.
fn timeout_ms(timeout: Option<Duration>) -> Option<i64> {
    timeout.map(|t| {
        i64::try_from(t.as_nanos().div_ceil(1_000_000).min(MAX_TIMEOUT_MS))
            .expect("at most 2^62 - 1")
    })
}

/// A Platform API client: `alien.<group>().<method>(..)` starts any Platform
/// API operation ([`operations::platform`]). Its `Debug` output never shows
/// the API key. The generated client it holds, whose `Debug` does
/// (docs/gaps.md#b22), stays private.
#[derive(Clone)]
pub struct Alien {
    client: alien_api::platform::PlatformClient,
}

impl fmt::Debug for Alien {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Alien")
            .field("server_url", &redact_query(&self.client.base_url))
            .field("api_key", &REDACTED)
            .field("workspace", &self.client.workspace)
            .field("timeout_ms", &self.client.timeout_ms)
            .finish()
    }
}

impl Alien {
    /// Creates a client. Fails with `INVALID_REQUEST` when there is no API
    /// key: [`Options::api_key`] is empty, or `None` with `ALIEN_API_KEY`
    /// unset or empty. Call [`shutdown`] before the process ends other than by
    /// exiting normally (a signal, an abort).
    pub fn new(options: Options) -> Result<Self, Error> {
        let api_key = options
            .api_key
            .unwrap_or_else(|| std::env::var(API_KEY_ENV).unwrap_or_default());
        if api_key.is_empty() {
            return Err(Error::Alien(AlienError {
                code: "INVALID_REQUEST".to_string(),
                message: format!("no API key: pass api_key or set {API_KEY_ENV}"),
                retryable: false,
                http_status_code: None,
                context: None,
                hint: None,
                request_id: None,
                source: None,
                internal: None,
            }));
        }
        Ok(Self {
            client: alien_api::platform::PlatformClient {
                workspace: options.workspace,
                timeout_ms: timeout_ms(options.timeout),
                ..alien_api::platform::PlatformClient::new(
                    options
                        .server_url
                        .unwrap_or_else(|| DEFAULT_SERVER_URL.to_string()),
                    api_key,
                )
            },
        })
    }

    /// Setup helpers that need the Platform API.
    pub fn setup(&self) -> ProjectSetup<'_> {
        ProjectSetup {
            client: &self.client,
        }
    }
}

/// A Manager API client, for example for the `managerUrl` and `token` that
/// `alien.commands().bootstrap(..)` returns: `manager.<group>().<method>(..)`
/// starts any Manager API operation ([`operations::manager`]). Its `Debug`
/// output never shows the token. The generated client it holds, whose
/// `Debug` does (docs/gaps.md#b22), stays private.
#[derive(Clone)]
pub struct AlienManager {
    client: alien_api::manager::ManagerClient,
}

impl fmt::Debug for AlienManager {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("AlienManager")
            .field("server_url", &redact_query(&self.client.base_url))
            .field("token", &self.client.token.as_ref().map(|_| REDACTED))
            .field("timeout_ms", &self.client.timeout_ms)
            .finish()
    }
}

impl AlienManager {
    /// Creates a client. The token is sent as a Bearer token on every
    /// operation when set; an empty token sends none. Call [`shutdown`] before
    /// the process ends other than by exiting normally (a signal, an abort).
    pub fn new(server_url: impl Into<String>, token: Option<String>) -> Self {
        let token = token.filter(|token| !token.is_empty());
        Self {
            client: alien_api::manager::ManagerClient {
                token,
                ..alien_api::manager::ManagerClient::new(server_url.into())
            },
        }
    }

    /// The client with a limit for each HTTP request, as [`Options::timeout`]
    /// sets it for [`Alien`] (`Duration::ZERO`: no limit). Without it, BAML's
    /// default of 5 minutes applies:
    /// `AlienManager::new(url, token).with_timeout(Duration::from_secs(30))`.
    pub fn with_timeout(mut self, timeout: Duration) -> Self {
        self.client.timeout_ms = timeout_ms(Some(timeout));
        self
    }
}

/// Setup helpers that need the Platform API.
pub struct ProjectSetup<'a> {
    client: &'a alien_api::platform::PlatformClient,
}

impl fmt::Debug for ProjectSetup<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ProjectSetup").finish_non_exhaustive()
    }
}

impl ProjectSetup<'_> {
    /// Fetches the project's AWS template and builds a quick-create link for it.
    pub async fn launch_url_for_project(
        &self,
        project: &str,
        region: &str,
        stack_name: &str,
        parameters: impl IntoIterator<Item = (String, String)>,
    ) -> Result<String, Error> {
        Ok(setup::launch_url_for_project(
            self.client,
            project.to_string(),
            region.to_string(),
            stack_name.to_string(),
            parameters.into_iter().collect(),
        )
        .await?)
    }
}

/// Builds an AWS CloudFormation quick-create link from a template URL.
pub async fn cloudformation_launch_url(input: CloudFormationLaunch) -> Result<String, Error> {
    Ok(setup::cloudformation_launch_url(input).await?)
}

#[cfg(test)]
mod tests {
    //! What the generated clients hold, which only the facade can see. The
    //! only test in this binary that writes the environment.
    use super::*;

    const KEY: &str = "alien_test_api_key_never_printed";

    #[test]
    fn clients_hold_the_key_token_and_timeout() {
        // SAFETY: the only test in this binary that touches the environment,
        // and the others do not read it.
        unsafe { std::env::set_var(API_KEY_ENV, KEY) };
        let from_env = Alien::new(Options::default()).expect("key from ALIEN_API_KEY");
        assert_eq!(from_env.client.api_key, KEY);
        let explicit = Alien::new(Options {
            api_key: Some("explicit".into()),
            ..Default::default()
        })
        .expect("explicit key");
        assert_eq!(explicit.client.api_key, "explicit");
        unsafe { std::env::remove_var(API_KEY_ENV) };

        // An empty token sends no Authorization header, as in the other SDKs.
        let manager = AlienManager::new("https://manager.example", Some(String::new()));
        assert_eq!(manager.client.token, None);

        // The timeout reaches the generated clients in whole milliseconds, rounded up.
        for (timeout, want) in [
            (None, None),
            (Some(Duration::from_millis(300)), Some(300)),
            (Some(Duration::from_micros(1500)), Some(2)),
            (Some(Duration::from_nanos(1)), Some(1)),
            (Some(Duration::ZERO), Some(0)),
            (Some(Duration::MAX), Some((1 << 62) - 1)),
        ] {
            let alien = Alien::new(Options {
                api_key: Some(KEY.into()),
                timeout,
                ..Default::default()
            })
            .expect("client");
            assert_eq!(alien.client.timeout_ms, want, "Options::timeout {timeout:?}");
            if let Some(timeout) = timeout {
                let manager = AlienManager::new("u", None).with_timeout(timeout);
                assert_eq!(manager.client.timeout_ms, want, "with_timeout {timeout:?}");
            }
        }
        assert_eq!(AlienManager::new("u", None).client.timeout_ms, None);
    }

    /// A generated error with this code, status and source, every other
    /// field set.
    fn generated(
        code: &str,
        http_status: Option<i64>,
        source: Option<alien_api::errors::AlienError>,
    ) -> alien_api::errors::AlienError {
        alien_api::errors::AlienError {
            code: code.to_string(),
            message: format!("{code} failed"),
            retryable: true,
            http_status,
            context: Some(
                [("details".to_string(), "{}".to_string())]
                    .into_iter()
                    .collect(),
            ),
            hint: Some(format!("{code} hint")),
            request_id: Some(format!("req_{code}")),
            source: source.map(Box::new),
            internal: Some(true),
        }
    }

    /// The codes of an error and its sources, as `std::error::Error::source()` gives them.
    fn sources(error: &(dyn std::error::Error + 'static)) -> Vec<String> {
        let mut codes = Vec::new();
        let mut next = Some(error);
        while let Some(level) = next {
            let level = level
                .downcast_ref::<AlienError>()
                .expect("every level is an AlienError");
            codes.push(level.code.clone());
            next = std::error::Error::source(level);
        }
        codes
    }

    #[test]
    fn the_conversion_keeps_every_field_and_the_source_chain() {
        use std::error::Error as _;

        let thrown = generated(
            "OUTER",
            Some(500),
            Some(generated(
                "INNER",
                Some(403),
                Some(generated("INNERMOST", None, None)),
            )),
        );
        let error = AlienError::from(thrown);
        assert_eq!(
            (
                error.code.as_str(),
                error.message.as_str(),
                error.retryable,
                error.http_status_code
            ),
            ("OUTER", "OUTER failed", true, Some(500))
        );
        assert_eq!(
            error.context.as_ref().map(|c| c["details"].as_str()),
            Some("{}")
        );
        assert_eq!(error.hint.as_deref(), Some("OUTER hint"));
        assert_eq!(error.request_id.as_deref(), Some("req_OUTER"));
        assert_eq!(error.internal, Some(true));
        let inner = error.source.as_deref().expect("a source");
        assert_eq!(
            (
                inner.code.as_str(),
                inner.http_status_code,
                inner.hint.as_deref(),
                inner.request_id.as_deref()
            ),
            ("INNER", Some(403), Some("INNER hint"), Some("req_INNER"))
        );
        let innermost = inner.source.as_deref().expect("a second source");
        assert_eq!(
            (innermost.code.as_str(), innermost.http_status_code),
            ("INNERMOST", None)
        );
        assert!(innermost.source.is_none() && innermost.source().is_none());

        // std::error::Error::source() walks the same chain, from the error
        // and from the `Error::Alien` that holds it; the BAML error that
        // carried the throw is not in it.
        assert_eq!(sources(&error), ["OUTER", "INNER", "INNERMOST"]);
        let held = Error::Alien(error.clone());
        assert_eq!(held.to_string(), "OUTER: OUTER failed");
        assert_eq!(
            sources(held.source().expect("the error's source")),
            ["INNER", "INNERMOST"]
        );
        let no_source = Error::Alien(AlienError::from(generated("ALONE", None, None)));
        assert!(no_source.source().is_none());
    }

    #[test]
    fn a_status_that_is_not_an_http_status_is_dropped_not_a_panic() {
        // The BAML code keeps a source level's status only from 100 to 599;
        // the conversion does not rely on that.
        for status in [70_000, -1, i64::MAX, i64::MIN, 65_536] {
            let error = AlienError::from(generated(
                "OUTER",
                Some(status),
                Some(generated("INNER", Some(status), None)),
            ));
            assert_eq!(error.http_status_code, None, "{status}");
            assert_eq!(
                error.source.expect("a source").http_status_code,
                None,
                "{status}"
            );
        }
        assert_eq!(
            AlienError::from(generated("E", Some(65_535), None)).http_status_code,
            Some(65_535)
        );
    }
}
