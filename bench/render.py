#!/usr/bin/env python3
"""Renders metrics/results.md from metrics/raw/results.json (bench/run.py)."""

from __future__ import annotations

import json
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
raw = json.loads((REPO / "metrics" / "raw" / "results.json").read_text())

# A run counts as final only if the 1-minute load average stayed at or below
# this for every sample (bench/run.py).
QUIET_LOAD = 2.0

COLUMNS = [("typescript", "TypeScript"), ("incumbent-typescript", "Incumbent TS"), ("python", "Python"),
           ("go", "Go"), ("rust", "Rust"), ("incumbent-rust", "Incumbent Rust")]
OURS = [("typescript", "TypeScript"), ("python", "Python"), ("go", "Go"), ("rust", "Rust")]


def med(values: list[float]) -> float:
    return statistics.median(values)


def iqr(values: list[float]) -> tuple[float, float]:
    if len(values) < 4:
        return min(values), max(values)
    q = statistics.quantiles(values, n=4)
    return q[0], q[2]


def mb(kb: float) -> str:
    return f"{kb / 1024:.1f}"


def all_loads() -> list[float]:
    loads = [x for c in raw["cold"].values() for x in c["load1"]]
    for section in ("warm_get_ns", "warm_helper_ns", "warm_noop_ns"):
        loads += [x for o in raw[section].values() for x in o["load1"]]
    loads += [x for size in raw["page_ms"].values() for o in size.values() for x in o["load1"]]
    return loads + [raw["load"]["start"][0], raw["load"]["end"][0]]


def fmt(value: float, digits: int) -> str:
    return f"{value:,.{digits}f}"


def cell(values: list[float] | None, digits: int, scale: float = 1.0) -> str:
    return "—" if not values else fmt(med(values) / scale, digits)


def spread(values: list[float], digits: int, scale: float = 1.0) -> str:
    lo, hi = iqr(values)
    return f"{fmt(lo / scale, digits)}–{fmt(hi / scale, digits)}"


def plural(count: int, one: str, many: str) -> str:
    return f"{count} {one if count == 1 else many}"


def load_range(loads: list[float]) -> str:
    return f"{min(loads):.1f}–{max(loads):.1f}"


cold, sizes, builds = raw["cold"], raw["sizes"], raw["builds"]
warm, helper, noop = raw["warm_get_ns"], raw["warm_helper_ns"], raw["warm_noop_ns"]
pages = raw["page_ms"]
m, s = raw["machine"], raw["settings"]
loads = all_loads()
provisional = s["quick"] or max(loads) > QUIET_LOAD
big, small = "2000", "20"


def cold_ms(name: str, mode: str) -> list[float] | None:
    return cold.get(f"{name}/{mode}", {}).get("ms")


def cold_rss(name: str, mode: str) -> list[float] | None:
    return cold.get(f"{name}/{mode}", {}).get("rss_kb")


def page(size: str, name: str) -> list[float] | None:
    return pages[size].get(name, {}).get("values")


def signed(value: float, digits: int) -> str:
    return f"{'+' if round(value, digits) >= 0 else '−'}{fmt(abs(value), digits)}"


def change(off: list[float], on: list[float], digits: int, scale: float = 1.0) -> str:
    return f"{signed((med(on) - med(off)) / scale, digits)} ({signed((med(on) / med(off) - 1) * 100, 0)}%)"


lines = ["# Measurements", ""]
if provisional:
    lines += [
        f"> **PROVISIONAL.** These numbers were measured while the machine was busy: the 1-minute load average was "
        f"{load_range(loads)} during the run ({m['cores']} cores){' and this was a --quick run' if s['quick'] else ''}. "
        f"Ratios between programs measured in the same run are more reliable than absolute times, but treat both as provisional. "
        f"Re-run `bench/run.sh` when `uptime` shows a load average below {QUIET_LOAD:.0f}; this banner disappears when every sample was taken at or below it.",
        "",
    ]
else:
    lines += [f"Measured on a quiet machine: the 1-minute load average stayed between {load_range(loads)} ({m['cores']} cores).", ""]
lines += [
    "Cold start, resident memory, warm per-call latency, large-page decode, the cost of telemetry, installed size and Rust "
    "build time, for the four BAML SDKs and Alien's current SDKs (the incumbents). Generated by `bench/render.py` from [`raw/results.json`](raw/results.json); "
    "regenerate with (bench/run.py):",
    "",
    "```sh",
    "ALIEN_REF=/path/to/alien bench/run.sh" + (f" --quiet-wait {s['quiet_wait_min']:g}" if s.get("quiet_wait_min") else ""),
    "```",
    "",
    f"**Machine:** {m['cores']} cores, {m['memory_gb']} GB, {m['os']}. Node {m['node']}, {m['python']}, "
    f"{m['go']}, {m['rustc']}. **Measured:** {raw['date']}.",
    "",
    f"**Builds.** BAML {raw['build']['baml_build']}. Incumbents built by `bench/build.sh` from Alien commit "
    f"`{raw['build']['alien_commit'][:12]}`: `@alienplatform/platform-api` (Speakeasy TypeScript, with the dependency versions Alien's "
    "`pnpm-lock.yaml` pins) and `alien-platform-api` (Progenitor Rust, default features: only the operations Alien itself calls). "
    "There is no Python or Go incumbent.",
    "",
    "**Method.** Every request goes to `bench/fixed-server.mjs`, a zero-latency server on 127.0.0.1 "
    "(`GET /v1/managers/{id}` returns one Manager, `GET /v1/managers?limit=N` returns N of them). Every process gets an empty "
    "`BAML_HOME` and telemetry off; the driver fails if a process writes any file there. The exception is the "
    "[telemetry-on](#telemetry-on-the-default) rows, measured with telemetry as an application gets it by default. "
    "Go and Rust load the runtime library "
    "from a local path. Programs are interleaved round-robin so that a burst of load spreads over all of them, and the "
    "1-minute load average is recorded with every sample. Tables show medians; ranges are the interquartile range (p25–p75).",
    "",
]
if raw.get("quiet"):
    lines += [
        f"**Quiet machine.** Before the measurements and before the Rust builds the driver waited up to {s['quiet_wait_min']:g} "
        f"minutes for a 1-minute load average below {QUIET_LOAD:g} (`--quiet-wait`). Load when each section started: "
        + ", ".join(f"{q['block']} {q['load1']:.2f}" + (f" (after {q['waited_s'] // 60} min)" if q["waited_s"] >= 60 else "") for q in raw["quiet"])
        + ".",
        "",
    ]
lines += [
    "## Summary",
    "",
    "| | " + " | ".join(label for _, label in COLUMNS) + " |",
    "|---|" + "---|" * len(COLUMNS),
    "| Cold start: process start to SDK loaded (ms) | " + " | ".join(cell(cold_ms(n, "import"), 1) for n, _ in COLUMNS) + " |",
    "| Cold start: process start to first `managers.get` result (ms) | " + " | ".join(cell(cold_ms(n, "get"), 1) for n, _ in COLUMNS) + " |",
    "| Resident memory after the first call (MB) | " + " | ".join(cell(cold_rss(n, "get"), 1, 1024) for n, _ in COLUMNS) + " |",
    "| Warm `managers.get`, per call (µs) | " + " | ".join(cell(warm.get(n, {}).get("values"), 0, 1000) for n, _ in COLUMNS) + " |",
    "| Warm `managers.get`, telemetry on (µs) | " + " | ".join(cell(warm.get(f"{n}+telemetry", {}).get("values"), 0, 1000) for n, _ in COLUMNS) + " |",
    f"| `managers.list`, page of {small} (ms) | " + " | ".join(cell(page(small, n), 2) for n, _ in COLUMNS) + " |",
    f"| `managers.list`, page of {int(big):,} (ms) | " + " | ".join(cell(page(big, n), 1) for n, _ in COLUMNS) + " |",
    f"| `managers.list`, page of {int(big):,}, telemetry on (ms) | " + " | ".join(cell(page(big, f"{n}+telemetry"), 1) for n, _ in COLUMNS) + " |",
    "| Installed size, runtime included (MB) | " + " | ".join(mb(sizes[n]["total_kb"]) for n, _ in COLUMNS) + " |",
    "",
    "## Cold start and resident memory",
    "",
    f"Process start to the first line the program prints, {s['runs']} runs each after one unrecorded round (OS file cache warm). "
    "`import` loads the SDK and builds a client; `get` also makes one `managers.get` call. "
    "RSS is `ps -o rss` right after that line. Go loads the BAML runtime library on the first call, so its `import` row is process start only.",
    "",
    "| Program | Mode | Median ms | p25–p75 ms | RSS MB | Load |",
    "|---|---|---|---|---|---|",
]
for key, c in cold.items():
    name, mode = key.split("/", 1)
    lines.append(f"| {name} | {mode} | {fmt(med(c['ms']), 1)} | {spread(c['ms'], 1)} | {mb(med(c['rss_kb']))} | {load_range(c['load1'])} |")

b, n = s["calls"]["warm_get"]
hb, hn = s["calls"]["warm_helper"]
lines += [
    "",
    "## Warm per-call latency",
    "",
    f"After a warm-up in each process: {plural(s['procs'], 'process', 'processes')} × {b} batches of {n} sequential `managers.get` calls to the local server; "
    f"the cost per call of each batch. `setup helper` ({s['procs']} × {hb} × {hn} calls) builds a CloudFormation link without any I/O, "
    "and `no-op` is a zero-argument BAML function that returns a constant, so it is the cost of crossing into the runtime and back.",
    "",
    "| Program | `managers.get` µs | p25–p75 | Setup helper µs | No-op µs | Load |",
    "|---|---|---|---|---|---|",
]
for name, label in COLUMNS:
    w = warm[name]["values"]
    h = helper.get(name, {}).get("values")
    o = noop.get(name, {}).get("values")
    lines.append(f"| {label} | {fmt(med(w) / 1000, 0)} | {spread(w, 0, 1000)} | {cell(h, 1, 1000)} | {cell(o, 1, 1000)} | "
                 f"{load_range(warm[name]['load1'] + helper.get(name, {}).get('load1', []) + noop.get(name, {}).get('load1', []))} |")
lines += [
    "",
    "**Connections.** Every SDK keeps its connection open between calls. For 500 sequential `managers.get` calls in one "
    "process, each BAML SDK opened 1 TCP connection, Alien's TypeScript SDK 2 and its Rust SDK 1; as a control, Python's "
    "`urllib` opened one per request. The BAML runtime has reused its HTTP clients across requests since BAML 0.23.0 "
    "(BAML #5373). This is a one-off count on 2026-10-26, over plain HTTP to the local server (`GET /stats` on "
    "`bench/fixed-server.mjs`; `bench/run.sh` does not re-count), so the TLS handshake against `https://api.alien.dev` "
    "was not measured.",
    "",
    "The setup helper's cost is mostly BAML code: compiling the region pattern on every call (a BAML constant can hold the "
    "compiled pattern since BAML 0.23.0, but the helper does not keep one, [gaps B17](../docs/gaps.md#b17)), building the link "
    "with string interpolation, which BAML 0.23.0 runs more slowly than `+`, and percent-encoding character by character in "
    "the interpreter. A setup link is built once per customer, so it does not matter there.",
    "",
    "## Large-page decode",
    "",
]
for size in (small, big):
    warmup, timed = s["pages"][size]
    lines += [
        f"`managers.list` returning {int(size):,} Managers ({raw['page_bytes'][size]:,} bytes of JSON): {plural(s['procs'], 'process', 'processes')} × "
        f"{timed} timed calls after {warmup} warm-up calls. `Node fetch + JSON.parse` and `Python urllib + json` are the same request without an SDK.",
        "",
        "| Program | Median ms | p25–p75 ms | µs per Manager | vs incumbent TS | RSS after MB | Load |",
        "|---|---|---|---|---|---|---|",
    ]
    inc = med(page(size, "incumbent-typescript"))
    for name, label in COLUMNS + [("baseline-node", "Node fetch + JSON.parse"), ("baseline-python", "Python urllib + json")]:
        v = page(size, name)
        o = pages[size][name]
        lines.append(f"| {label} | {fmt(med(v), 2)} | {spread(v, 2)} | {fmt(med(v) * 1000 / int(size), 1)} | {med(v) / inc:.1f}× | "
                     f"{mb(med(o['rss_kb']))} | {load_range(o['load1'])} |")
    lines.append("")
lines += [
    "Where the large-page time goes (a one-off profile on 2026-10-26 with macOS `sample` and a symbolized build of the BAML 0.23.0 "
    "release commit, whose timings matched the published build; TypeScript, page of 2,000; `bench/run.sh` does not re-profile): "
    "about 72% of the call is inside the BAML runtime, the same work in every language. Of that runtime time, 6% turns the JSON "
    "text into typed values (`baml.json.decode`, one pass since 0.23.0), 35% converts those values into the tree the runtime hands "
    "to the host, 20% copies that tree once more, 21% encodes it as protobuf and 11% frees the copies; HTTP and BAML's garbage "
    "collection are about 2% each. The other 28% is the host side: decoding the protobuf and building the generated classes in "
    "JavaScript (24%), and V8's garbage collection (4%), whose helper threads spend about another 14% of the call's time in parallel. "
    "Python's host side is larger (pydantic models). In the 2026-10-21 profile (BAML 0.22.2), decoding the JSON was 56% of the "
    "runtime time; now handing the result to the host is most of it.",
    "",
]
off, on = OURS, [(f"{n}+telemetry", label) for n, label in OURS]
lines += [
    "## Telemetry on (the default)",
    "",
    "The SDKs record telemetry unless `ALIEN_TELEMETRY=off` ([docs/telemetry.md](../docs/telemetry.md)). These rows run the same "
    "programs with telemetry as an application gets it by default: `ALIEN_TELEMETRY` unset, no Boundary API key and an empty "
    "`BAML_HOME`, so the runtime records into `BAML_HOME` and sends nothing. They ran interleaved with the telemetry-off runs above, "
    f"with the same calls: {plural(s['procs'], 'process', 'processes')} × {b} batches of {n} `managers.get` calls, and "
    f"{plural(s['procs'], 'process', 'processes')} × {s['pages'][big][1]} pages of {int(big):,}.",
    "",
    f"| SDK | `managers.get` µs, off | on | Change | Page of {int(big):,} ms, off | on | Change | Files recorded per process (`managers.get` / page) | Load |",
    "|---|---|---|---|---|---|---|---|---|",
]
for (name, label), (tname, _) in zip(off, on):
    w_off, w_on, p_off, p_on = warm[name]["values"], warm[tname]["values"], page(big, name), page(big, tname)
    files = f"{fmt(med(warm[tname]['files']), 0)} / {fmt(med(pages[big][tname]['files']), 0)}"
    lines.append(f"| {label} | {fmt(med(w_off) / 1000, 0)} | {fmt(med(w_on) / 1000, 0)} | {change(w_off, w_on, 0, 1000)} | "
                 f"{fmt(med(p_off), 1)} | {fmt(med(p_on), 1)} | {change(p_off, p_on, 1)} | {files} | "
                 f"{load_range(warm[tname]['load1'] + pages[big][tname]['load1'])} |")
lines += [
    "",
    "## Installed size",
    "",
    "What an application installs. TypeScript: `npm install` of the packed SDK"
    + (" and the packed local BAML runtime package" if raw["build"]["baml_local_build"] else "")
    + " (production dependencies; only this platform's native addon). Python: `uv pip install` of a package built from `sdk/python`"
    + (" with the local runtime wheel" if raw["build"]["baml_local_build"] else "")
    + ". Go and Rust: the release-built bench program plus the runtime library it loads (Go built with default flags, symbols kept).",
    "",
    "| Package | Installed MB | Biggest parts (MB) |",
    "|---|---|---|",
]


def parts(size: dict, count: int = 4) -> str:
    return ", ".join(f"{k} {mb(v)}" for k, v in list(size["packages_kb"].items())[:count])


for name, label in [("typescript", "TypeScript `@alien-baml/sdk`"), ("incumbent-typescript", "Incumbent `@alienplatform/platform-api`"),
                    ("python", "Python `alien-sdk`"), ("go", "Go (bench program)"), ("rust", "Rust (bench program)"),
                    ("incumbent-rust", "Incumbent Rust (bench program)")]:
    lines.append(f"| {label} | {mb(sizes[name]['total_kb'])} | {parts(sizes[name])} |")
g = sizes["generated_source_kb"]
lines += [
    "",
    f"The BAML runtime (native addon, Python extension or `libbridge_cffi`) is about 30 MB of every BAML package. Generated SDK "
    f"source on disk (`sdk/*/baml_sdk`): TypeScript {mb(g['typescript'])} MB, Python {mb(g['python'])} MB, Go {mb(g['go'])} MB, "
    f"Rust {mb(g['rust'])} MB; most of it is BAML's standard library, which every generated SDK includes.",
    "",
]

bl, runs = builds["lines"], builds["runs"]
build_loads = [x for program in builds["programs"].values() for profile in program.values() for x in profile["load1"]]
lines += [
    "## Rust build time and generated code",
    "",
    "Clean builds of the Rust bench program (`bench/rust`: the SDK and every dependency, in a fresh target directory, "
    "downloads fetched first) and of the same program on Alien's Progenitor client (`bench/incumbent-rust`), with default "
    "features (only the Platform operations Alien's own code calls) and with `full-api` (every Platform operation). "
    "\"SDK only\" then rebuilds just the generated SDK crate and the program. "
    f"Seconds, median of {plural(runs, 'run', 'runs')}; the load average at the start of each run was {load_range(build_loads)}, "
    "most of it from the previous build. The BAML SDK's Rust code is generated before the build (`baml generate`) and covers "
    "every Platform and Manager operation; Progenitor generates its client in a build script, so its times include generation.",
    "",
    "| Program | Generated lines | dev, clean | dev, SDK only | release, clean | release, SDK only |",
    "|---|---|---|---|---|---|",
]
for name, label, generated in [
    ("rust", "BAML Rust SDK", f"{bl['rust']['total']:,} ({bl['rust']['api']:,} for the API, the rest BAML's standard library)"),
    ("progenitor-default", "Progenitor, default features", f"{bl['progenitor-default']:,}"),
    ("progenitor-full-api", "Progenitor, `full-api`", f"{bl['progenitor-full-api']:,}"),
]:
    t = builds["programs"][name]
    lines.append(f"| {label} | {generated} | " + " | ".join(
        fmt(med(t[profile][key]), 1) for profile in ("dev", "release") for key in ("clean_s", "crate_only_s")) + " |")
lines += [
    "",
    "Alien's build fails when the default Progenitor client generates more than 270,000 lines "
    "(`client-sdks/platform/rust/build.rs`); `full-api` has no limit.",
    "",
]
(REPO / "metrics" / "results.md").write_text("\n".join(lines))
print("wrote metrics/results.md")
