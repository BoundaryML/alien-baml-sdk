//! Calls operations through Alien's Progenitor Rust clients, one per line of
//! stdin, and prints what each returned, one JSON line per call. run.mjs
//! drives it (conformance/incumbents/README.md).
//!
//! A call: `{"service": "platform" | "manager", "op": <client method>,
//! "base_url", "bearer", "timeout_ms", "params": {<builder method>: <JSON>},
//! "body": <JSON>}`. The answer is one of:
//! - `{"ok": <the decoded response, serialized again>}`;
//! - `{"error": {...}}`: the error as Alien's own code reads it
//!   (`convert_sdk_error`, which `into_sdk_error()` calls), plus the
//!   client's error variant;
//! - `{"rejected": {"argument", "message"}}`: the client's types refuse an
//!   argument, so no request is sent;
//! - `{"harness": <message>}`: the call does not fit the client (unknown
//!   operation or parameter); run.mjs fails on it.
//!
//! The operation table (`PROGENITOR_TABLE`) is generated by run.mjs from the
//! client's generated code: one row per operation, setting each parameter
//! through its builder method with the type that method takes.

// run.mjs first builds the program with an empty table, to have the clients built.
#![allow(dead_code)]

use std::{io::BufRead, time::Duration};

use alien_manager_api as manager;
use alien_platform_api as platform;
use futures::TryStreamExt;
use platform::{ByteStream, Error, ResponseValue};
use reqwest::header::{AUTHORIZATION, HeaderMap, HeaderValue};
use serde::{Serialize, de::DeserializeOwned};
use serde_json::{Map, Value, json};

include!(env!("PROGENITOR_TABLE"));

/// The arguments of one call, taken by the table's rows.
struct Args {
    params: Map<String, Value>,
    body: Option<Value>,
}

impl Args {
    /// The parameter `name` as the type its builder method takes.
    fn take<T: DeserializeOwned>(&mut self, name: &str) -> Result<Option<T>, Value> {
        self.params.remove(name).map(|v| convert(name, v)).transpose()
    }

    fn body<T: DeserializeOwned>(&mut self) -> Result<Option<T>, Value> {
        self.body.take().map(|v| convert("body", v)).transpose()
    }

    /// Fails when the call has an argument the operation does not take.
    fn finish(&self) -> Result<(), Value> {
        match (self.params.keys().next(), &self.body) {
            (Some(name), _) => Err(json!({ "harness": format!("the operation has no parameter `{name}`") })),
            (None, Some(_)) => Err(json!({ "harness": "the operation takes no body" })),
            (None, None) => Ok(()),
        }
    }
}

fn convert<T: DeserializeOwned>(name: &str, value: Value) -> Result<T, Value> {
    serde_json::from_value(value).map_err(|e| json!({ "rejected": { "argument": name, "message": e.to_string() } }))
}

fn variant<E>(error: &Error<E>) -> &'static str {
    match error {
        Error::InvalidRequest(_) => "InvalidRequest",
        Error::CommunicationError(_) => "CommunicationError",
        Error::InvalidUpgrade(_) => "InvalidUpgrade",
        Error::ErrorResponse(_) => "ErrorResponse",
        Error::ResponseBodyError(_) => "ResponseBodyError",
        Error::InvalidResponsePayload(..) => "InvalidResponsePayload",
        Error::UnexpectedResponse(_) => "UnexpectedResponse",
        Error::Custom(_) => "Custom",
    }
}

fn ok<T: Serialize>(value: T) -> Value {
    match serde_json::to_value(value) {
        Ok(v) => json!({ "ok": v }),
        Err(e) => json!({ "harness": format!("cannot serialize the response: {e}") }),
    }
}

/// An `AlienError` from `convert_sdk_error`, as JSON.
macro_rules! alien_error {
    ($variant:expr, $e:expr) => {{
        let e = $e;
        json!({ "error": {
            "variant": $variant,
            "code": e.code,
            "message": e.message,
            "retryable": e.retryable,
            "http_status": e.http_status_code,
            "context": e.context,
            "hint": e.hint,
        } })
    }};
}

/// A Platform operation's result (its errors are `types::ApiError` bodies).
fn platform_outcome<T: Serialize>(r: Result<ResponseValue<T>, Error<platform::types::ApiError>>) -> Value {
    match r {
        Ok(v) => ok(v.into_inner()),
        Err(e) => {
            let name = variant(&e);
            alien_error!(name, platform::convert_sdk_error(e))
        }
    }
}

/// A Platform operation whose success may have no body: the client hands
/// back the bytes, and its caller decodes them.
async fn platform_stream_outcome(r: Result<ResponseValue<ByteStream>, Error<platform::types::ApiError>>) -> Value {
    match r {
        Ok(v) => match v.into_inner().into_inner().try_fold(Vec::new(), |mut all, chunk| async move {
            all.extend_from_slice(&chunk);
            Ok(all)
        })
        .await
        {
            Ok(bytes) if bytes.is_empty() => json!({ "ok": null }),
            Ok(bytes) => match serde_json::from_slice::<Value>(&bytes) {
                Ok(value) => json!({ "ok": value }),
                Err(e) => json!({ "error": { "variant": "(caller's decoding)", "code": "(invalid JSON)", "message": e.to_string() } }),
            },
            Err(e) => json!({ "error": { "variant": "(body read)", "code": "(body read)", "message": e.to_string() } }),
        },
        Err(e) => {
            let name = variant(&e);
            alien_error!(name, platform::convert_sdk_error(e))
        }
    }
}

/// A Platform operation that declares no error body: `convert_sdk_error`
/// does not take its errors, so they are the client's own.
async fn platform_untyped_outcome<T: Serialize>(r: Result<ResponseValue<T>, Error<()>>) -> Value {
    match r {
        Ok(v) => ok(v.into_inner()),
        Err(e) => json!({ "error": {
            "variant": variant(&e),
            "code": format!("({})", variant(&e)),
            "http_status": e.status().map(|s| s.as_u16()),
            // Not the response's Debug text: it has the Date header.
            "message": match &e {
                Error::UnexpectedResponse(response) => format!("Unexpected response: {}", response.status()),
                other => other.to_string(),
            },
        } }),
    }
}

/// A Manager operation's result (its spec declares no error bodies, so
/// `convert_sdk_error` reads them).
async fn manager_outcome<T: Serialize>(r: Result<ResponseValue<T>, manager::Error<()>>) -> Value {
    match r {
        Ok(v) => ok(v.into_inner()),
        Err(e) => {
            let name = variant(&e);
            alien_error!(name, manager::convert_sdk_error(e).await)
        }
    }
}

/// The HTTP client a Rust program gives these clients: the bearer token as a
/// default header (as Alien's CLI does), and the timeouts of `Client::new`
/// (15 s) unless the scenario sets one.
fn http(bearer: Option<&str>, timeout_ms: Option<u64>) -> Result<reqwest::Client, String> {
    let mut headers = HeaderMap::new();
    if let Some(token) = bearer {
        let value = HeaderValue::from_str(&format!("Bearer {token}")).map_err(|e| e.to_string())?;
        headers.insert(AUTHORIZATION, value);
    }
    let default = Duration::from_secs(15);
    reqwest::ClientBuilder::new()
        .connect_timeout(default)
        .timeout(timeout_ms.map_or(default, Duration::from_millis))
        .default_headers(headers)
        .build()
        .map_err(|e| e.to_string())
}

async fn call(line: &str) -> Value {
    let request: Value = match serde_json::from_str(line) {
        Ok(v) => v,
        Err(e) => return json!({ "harness": format!("bad call: {e}") }),
    };
    let text = |key: &str| request[key].as_str().map(str::to_string);
    let (Some(service), Some(op), Some(base_url)) = (text("service"), text("op"), text("base_url")) else {
        return json!({ "harness": "a call needs service, op and base_url" });
    };
    let http = match http(text("bearer").as_deref(), request["timeout_ms"].as_u64()) {
        Ok(c) => c,
        Err(e) => return json!({ "harness": format!("HTTP client: {e}") }),
    };
    let mut args = Args {
        params: request["params"].as_object().cloned().unwrap_or_default(),
        body: request.get("body").cloned().filter(|b| !b.is_null()),
    };
    let result = match service.as_str() {
        "platform" => platform_call(&platform::Client::new_with_client(&base_url, http), &op, &mut args).await,
        "manager" => manager_call(&manager::Client::new_with_client(&base_url, http), &op, &mut args).await,
        other => Err(json!({ "harness": format!("unknown service {other}") })),
    };
    result.unwrap_or_else(|v| v)
}

#[tokio::main(flavor = "current_thread")]
async fn main() {
    for line in std::io::stdin().lock().lines() {
        let line = line.expect("read stdin");
        println!("{}", call(&line).await);
    }
}
