//! What the importer did that a reader should know about, rendered to
//! `docs/importer-coverage.md`.

use std::collections::{BTreeMap, BTreeSet};

/// Counts are of schemas as lowered, before identical classes merge.
#[derive(Default)]
pub struct Coverage {
    pub counts: BTreeMap<String, usize>,
    /// (class, wire name, BAML name, pointer)
    pub renames: BTreeSet<(String, String, String, String)>,
    /// (pointer, reason)
    pub json_fallbacks: BTreeSet<(String, String)>,
    /// (pointer, note)
    pub notes: BTreeSet<(String, String)>,
}

impl Coverage {
    pub fn count(&mut self, what: &str) {
        *self.counts.entry(what.to_string()).or_default() += 1;
    }
    pub fn rename(&mut self, class: &str, wire: &str, name: &str, pointer: &str) {
        self.renames.insert((class.to_string(), wire.to_string(), name.to_string(), pointer.to_string()));
    }
    pub fn json_fallback(&mut self, pointer: &str, reason: &str) {
        self.json_fallbacks.insert((pointer.to_string(), reason.to_string()));
    }
    pub fn note(&mut self, pointer: &str, note: &str) {
        self.notes.insert((pointer.to_string(), note.to_string()));
    }
}

/// `docs/importer-coverage.md`.
pub fn render(reports: &[crate::ServiceReport]) -> String {
    let mut out = String::from(
        "# Importer coverage\n\n\
         Generated by `tools/openapi2baml` (see its DESIGN.md); do not edit. It lists what the\n\
         importer imported, every field it had to rename, and every schema it could only type as\n\
         `json`. Counts other than classes and type aliases are of schemas as lowered, before\n\
         identical classes merge.\n",
    );
    for report in reports {
        let c = &report.coverage;
        out.push_str(&format!(
            "\n## {}\n\n`{}` ({})\n\n| | Count |\n|---|---|\n| Operations imported | {} of {} |\n| Classes | {} |\n| Type aliases | {} |\n",
            report.name, report.spec, report.digest, report.operations, report.total_operations, report.classes, report.aliases
        ));
        for (what, count) in &c.counts {
            out.push_str(&format!("| {} | {count} |\n", capitalize(what)));
        }
        out.push_str(&format!("| Renamed fields | {} |\n| Typed as `json` | {} |\n", c.renames.len(), c.json_fallbacks.len()));

        out.push_str("\n### Renamed fields\n\n");
        if c.renames.is_empty() {
            out.push_str("None.\n");
        } else {
            out.push_str("| Class | Wire name | Field | Schema |\n|---|---|---|---|\n");
            for (class, wire, name, pointer) in &c.renames {
                out.push_str(&format!("| `{class}` | `{wire}` | `{name}` | `{pointer}` |\n"));
            }
        }
        out.push_str("\n### Typed as `json`\n\n");
        if c.json_fallbacks.is_empty() {
            out.push_str("None.\n");
        } else {
            out.push_str("| Schema | Why |\n|---|---|\n");
            for (pointer, reason) in &c.json_fallbacks {
                out.push_str(&format!("| `{pointer}` | {reason} |\n"));
            }
        }
        if !c.notes.is_empty() {
            out.push_str("\n### Notes\n\n| Schema | Note |\n|---|---|\n");
            for (pointer, note) in &c.notes {
                out.push_str(&format!("| `{pointer}` | {note} |\n"));
            }
        }
    }
    out
}

fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    chars.next().map(|c| c.to_uppercase().chain(chars).collect()).unwrap_or_default()
}
